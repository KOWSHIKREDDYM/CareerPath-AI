import os
import sqlite3
from pathlib import Path

import psycopg
from psycopg.rows import dict_row

BASE_DIR = Path(__file__).resolve().parent.parent
DATABASE_URL = os.getenv("DATABASE_URL")


def get_connection():
    if DATABASE_URL:
        # Render may provide a postgres:// URL; psycopg accepts postgresql://.
        database_url = DATABASE_URL
        if database_url.startswith("postgres://"):
            database_url = "postgresql://" + database_url[len("postgres://"):]

        return psycopg.connect(database_url, row_factory=dict_row)

    # Local development continues to use SQLite.
    connection = sqlite3.connect(BASE_DIR / "careerpath.db")
    connection.row_factory = sqlite3.Row
    return connection


def init_database():
    connection = get_connection()
    is_postgres = bool(DATABASE_URL)

    if is_postgres:
        id_column = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        timestamp_type = "TIMESTAMP DEFAULT CURRENT_TIMESTAMP"
        user_id_type = "BIGINT"
    else:
        id_column = "INTEGER PRIMARY KEY AUTOINCREMENT"
        timestamp_type = "TIMESTAMP DEFAULT CURRENT_TIMESTAMP"
        user_id_type = "INTEGER"

    try:
        cursor = connection.cursor()

        cursor.execute(f"""
            CREATE TABLE IF NOT EXISTS users (
                id {id_column},
                name TEXT NOT NULL,
                email TEXT UNIQUE NOT NULL,
                password_hash TEXT NOT NULL,
                created_at {timestamp_type}
            )
        """)

        cursor.execute(f"""
            CREATE TABLE IF NOT EXISTS profiles (
                id {id_column},
                user_id {user_id_type} NOT NULL,
                branch TEXT,
                year TEXT,
                current_skills TEXT,
                target_career TEXT,
                FOREIGN KEY (user_id) REFERENCES users(id)
            )
        """)

        cursor.execute(f"""
            CREATE TABLE IF NOT EXISTS career_results (
                id {id_column},
                user_id {user_id_type} NOT NULL,
                recommended_career TEXT,
                readiness_percentage INTEGER,
                result_json TEXT,
                created_at {timestamp_type},
                FOREIGN KEY (user_id) REFERENCES users(id)
            )
        """)

        connection.commit()
    finally:
        connection.close()